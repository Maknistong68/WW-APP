export type IconName = keyof typeof ICONS

export default function Icon({
  name,
  size = 24,
  strokeWidth = 2,
  fill = false,
  className,
}: {
  name: IconName
  size?: number
  /** Kept for old call sites: 2.4+ = bold. */
  strokeWidth?: number
  fill?: boolean
  className?: string
}) {
  const C = ICONS[name]
  return (
    <C
      className={className}
      size={size}
      weight={fill ? 'fill' : strokeWidth >= 2.4 ? 'bold' : 'regular'}
      aria-hidden="true"
      focusable="false"
    />
  )
}
