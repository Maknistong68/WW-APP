// The Worker Welfare audit by place: the same 118 questions, grouped by where the
// auditor is (the office, with the workers, on site) instead of the checklist's
// A–N order, each with a short reminder to read at a glance while walking. Every
// question is in exactly one place (welfareWalk.test.ts). The full question is
// always shown with it; answers, scores and the report don't change.

export interface WalkPlace {
  key: 'policies' | 'files' | 'workers' | 'site'
  title: string
  /** Where / with whom. */
  hint: string
  items: { code: string; reminder: string }[]
}

const place = (key: WalkPlace['key'], title: string, hint: string, items: [string, string][]): WalkPlace => ({
  key,
  title,
  hint,
  items: items.map(([code, reminder]) => ({ code, reminder })),
})

